   public FrmServicioTuristico(GestorEntidades gestor) {
       initComponents();


    this.gestor = gestor;

    cargarGuias();
    cargarTransportes();

    CmbTipoServicio.removeAllItems();


    CmbTipoServicio.addItem("Paseo Lacustre");
    CmbTipoServicio.addItem("Ruta Gastronómica");
    CmbTipoServicio.addItem("Excursión Cultural");


    CmbTipoServicio.setSelectedIndex(0);


    actualizarCampos();


}
    
   private void cargarGuias() {

        cmbGuia.removeAllItems();

           for (Registrable r : gestor.getEntidades()) {

            if (r instanceof Guia guia) {

                cmbGuia.addItem(guia.getNombre());

            }

        }

    }
    private void cargarTransportes() {

        cmbTransporte.removeAllItems();

        for (Registrable r : gestor.getEntidades()) {

            if (r instanceof Transporte transporte) {

                cmbTransporte.addItem(transporte.getIdentificador());

            }
        }
   }
   private void actualizarCampos() {

    if (CmbTipoServicio.getSelectedItem() == null) {
          return;
      }

      String tipo = CmbTipoServicio.getSelectedItem().toString();

      switch (tipo) {

            case "Paseo Lacustre":

                lblDato1.setText("Lago");
                lblDato2.setText("Tipo de recorrido");
                lblDato3.setText("Tipo de embarcación");

                break;


            case "Ruta Gastronómica":

                lblDato1.setText("Restaurante");
                lblDato2.setText("Tipo gastronomía");
                lblDato3.setText("Cantidad de paradas");

                break;


            case "Excursión Cultural":

                lblDato1.setText("Lugar cultural");
                lblDato2.setText("Tipo patrimonio");
                lblDato3.setText("Entrada incluida");

                break;
        }
    }

