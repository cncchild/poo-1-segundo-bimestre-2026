    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
             
  try {

        int id = gestor.generarNuevoId();

        String nombre = IngreseNombre.getText();
        String descripcion = IngreseDescripcion.getText();
        String duracion = IngreseDuracion.getText();
        double precio = Double.parseDouble(IngresePrecio.getText());

        String lago = TxtDato1.getText();
        String recorrido = TxtDato2.getText();
        String embarcacion = TxtDato3.getText();
        Guia guia = (Guia) cmbGuia.getSelectedItem();

        Transporte transporte =
                (Transporte) cmbTransporte.getSelectedItem();
   

        PaseoLacustre paseo = new PaseoLacustre(
                id,
                nombre,
                descripcion,
                duracion,
                precio,
                guia,
                transporte,
                lago,
                recorrido,
                embarcacion
        );

        gestor.agregarEntidad(paseo);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Servicio registrado correctamente."
        );


    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage()
            );

        }
    }//GEN-LAST:event_GuardarActionPerformed

